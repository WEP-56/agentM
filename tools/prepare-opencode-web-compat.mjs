import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'uiux-design/package.json'));
const { buildSync, version: esbuildVersion } = require('esbuild');
const packageDir = path.join(root, 'tools/opencode-web-compat');
const meta = JSON.parse(fs.readFileSync(path.join(packageDir, 'node_modules/core-js/package.json'), 'utf8'));
if (meta.version !== '3.41.0') throw Error('Unexpected core-js version');
const output = path.join(root, 'android/app/src/main/assets/opencode-web-compat.js');
buildSync({ entryPoints: [path.join(packageDir, 'entry.js')], outfile: output, bundle: true, minify: true,
  platform: 'browser', format: 'iife', target: 'chrome110', legalComments: 'inline', charset: 'ascii',
  banner: { js: '/* agentM WebUI compatibility: core-js 3.41.0 (MIT) and agentM AbortSignal.any; generated by tools/prepare-opencode-web-compat.mjs. */' } });
fs.copyFileSync(path.join(packageDir, 'node_modules/core-js/LICENSE'), path.join(root, 'android/app/src/main/assets/licenses/core-js-MIT.txt'));
const lock = JSON.parse(fs.readFileSync(path.join(packageDir, 'package-lock.json'), 'utf8')).packages['node_modules/core-js'];
const digest = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
fs.writeFileSync(path.join(root, 'docs/research/agent-packages/opencode-web-compat.json'), JSON.stringify({
  package: 'core-js', version: meta.version, license: meta.license, url: lock.resolved, integrity: lock.integrity,
  apis: ['Map.groupBy', 'Promise.withResolvers', 'AbortSignal.any'], esbuildVersion, target: 'chrome110',
  entrySha256: digest(path.join(packageDir, 'entry.js')), assetSha256: digest(output), assetBytes: fs.statSync(output).size,
  abortSignalSourceSha256: digest(path.join(packageDir, 'abort-signal-any.js')),
  scope: 'Document-start script, exact active OpenCode or DSH loopback origin, no native bridge, no override of existing native APIs'
}, null, 2) + '\n');
console.log(`Generated OpenCode WebUI compatibility: ${fs.statSync(output).size} bytes`);
